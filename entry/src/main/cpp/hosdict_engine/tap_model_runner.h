namespace hoskey::engine {

struct TapModelAssetBuffer {
  const uint8_t* data = nullptr;
  size_t size = 0;
};

struct TapModelAssets {
  TapModelAssetBuffer bundle;
  TapModelAssetBuffer feature_schema;
  TapModelAssetBuffer ranker;
  TapModelAssetBuffer classifier;
};

struct TapModelTouchPoint {
  double x = 0.0;
  double y = 0.0;
  uint32_t key_code = 0;
};

// Non-geometric values supplied by the active LM/transfeme pipeline. Geometry,
// priors, tap likelihood, is_same and the five pool statistics are generated by
// TapModelRunner from the exact bundle and therefore cannot be spoofed by the
// caller.
struct TapModelSemanticFeatures {
  float char_lm_mod = 0.0f;
  float word_lm_1 = 0.0f;
  float word_lm_cond_1 = 0.0f;
  float neural_char_lm_n = 0.0f;
  float neural_char_lm_cond_n = 0.0f;
  float neural_char_lm_cond_log_n = 0.0f;
  float neural_char_lm_per_letter_n = 0.0f;
  float context_prefix_len = 0.0f;
  float context_last_word_len = 0.0f;
  float distance_transfeme_original_correction_m = 0.0f;
  float distance_transfeme_correction_original_m = 0.0f;
  float neural_word_lm_cond_max = 0.0f;
  float neural_word_lm_cond_sum = 0.0f;
  float neural_word_lm_cond_avg = 0.0f;
};

struct TapModelPairRequest {
  std::string original;
  std::string correction;
  std::string layout = "android_ru_east_slavic_separate_comma";
  uint32_t keyboard_width = 0;
  uint32_t keyboard_height = 0;
  std::vector<TapModelTouchPoint> touches;
  TapModelSemanticFeatures original_semantics;
  TapModelSemanticFeatures correction_semantics;
};

struct TapModelPairResult {
  std::array<float, 38> original_features{};
  std::array<float, 38> correction_features{};
  double original_rank_score = 0.0;
  double correction_rank_score = 0.0;
  double classifier_probability = 0.0;
  bool should_autocorrect = false;
  bool model_engaged = false;
  std::string diagnostics;
};

// Exact Yandex 122.5 TapModel executor:
//   strict protobuf bundle + exact 33+5 feature order
//   -> 38-feature CatBoost ranker
//   -> [rank_o, features_o, rank_c, features_c] classifier (78 values).
class TapModelRunner {
 public:
  static constexpr size_t kBaseFeatureCount = 33;
  static constexpr size_t kRankerFeatureCount = 38;
  static constexpr size_t kClassifierFeatureCount = 78;
  static constexpr double kClassifierThreshold = 0.5;

  [[nodiscard]] Status Load(const TapModelAssets& assets);
  void Reset();

  [[nodiscard]] Status BuildPairFeatures(
      const TapModelPairRequest& request,
      std::array<float, kRankerFeatureCount>* original,
      std::array<float, kRankerFeatureCount>* correction) const;
  [[nodiscard]] Status EvaluatePair(const TapModelPairRequest& request,
                                    TapModelPairResult* result) const;

  [[nodiscard]] double ScoreRankerFeatures(
      const std::array<float, kRankerFeatureCount>& features) const;
  [[nodiscard]] double ScoreClassifierFeatures(
      double original_score,
      const std::array<float, kRankerFeatureCount>& original,
      double correction_score,
      const std::array<float, kRankerFeatureCount>& correction) const;

  [[nodiscard]] bool is_loaded() const { return loaded_; }
  [[nodiscard]] size_t layout_count() const { return bundle_.layout_count(); }
  [[nodiscard]] size_t key_count() const { return bundle_.key_count(); }
  [[nodiscard]] uint32_t ranker_feature_count() const {
    return ranker_.feature_count();
  }
  [[nodiscard]] uint32_t classifier_feature_count() const {
    return classifier_.feature_count();
  }
  [[nodiscard]] uint64_t ranker_invocation_count() const {
    return ranker_invocation_count_.load(std::memory_order_relaxed);
  }
  [[nodiscard]] uint64_t ranker_scored_count() const {
    return ranker_scored_count_.load(std::memory_order_relaxed);
  }
  [[nodiscard]] uint64_t classifier_invocation_count() const {
    return classifier_invocation_count_.load(std::memory_order_relaxed);
  }
  [[nodiscard]] uint64_t classifier_scored_count() const {
    return classifier_scored_count_.load(std::memory_order_relaxed);
  }
  [[nodiscard]] std::string diagnostics() const;

 private:
  bool loaded_ = false;
  TapModelBundle bundle_;
  ObliviousTreeModel ranker_;
  ObliviousTreeModel classifier_;
  mutable std::mutex score_mutex_;
  mutable std::atomic<uint64_t> ranker_invocation_count_{0};
  mutable std::atomic<uint64_t> ranker_scored_count_{0};
  mutable std::atomic<uint64_t> classifier_invocation_count_{0};
  mutable std::atomic<uint64_t> classifier_scored_count_{0};
  mutable std::atomic<uint64_t> rejected_count_{0};
};

}  // namespace hoskey::engine
